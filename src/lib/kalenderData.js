export function formatIndoDate(dateStr) {
  if (!dateStr) return '';
  const parts = dateStr.split('-');
  if (parts.length !== 3) return dateStr;
  const day = parts[2];
  const mIdx = parseInt(parts[1], 10) - 1;
  const year = parts[0];
  return `${day} ${MONTH_NAMES_INDO[mIdx]} ${year}`;
}

export function formatIndoDateRange(startDate, endDate) {
  if (!startDate) return '-';
  if (!endDate || startDate === endDate) return formatIndoDate(startDate);
  const d1 = startDate.split('-');
  const d2 = endDate.split('-');
  if (d1.length === 3 && d2.length === 3) {
    if (d1[0] === d2[0] && d1[1] === d2[1]) {
      return `${d1[2]} - ${d2[2]} ${MONTH_NAMES_INDO[parseInt(d1[1], 10) - 1]} ${d1[0]}`;
    } else if (d1[0] === d2[0]) {
      return `${d1[2]} ${MONTH_NAMES_INDO[parseInt(d1[1], 10) - 1]} - ${d2[2]} ${MONTH_NAMES_INDO[parseInt(d2[1], 10) - 1]} ${d1[0]}`;
    } else {
      return `${formatIndoDate(startDate)} - ${formatIndoDate(endDate)}`;
    }
  }
  return `${startDate} - ${endDate}`;
}

